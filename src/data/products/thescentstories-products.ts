import { Product, ProductFormat, FragranceFamily, Occasion, Season, Gender } from '@/types/product';
import { applyTssCanonicalImages } from './thescentstories-images';

type Draft = {
  id: string;
  slug: string;
  name: string;
  houseBrand: string;
  format: ProductFormat;
  size: string;
  price: number;
  originalPrice?: number;
  gender: Gender;
  fragranceFamily: FragranceFamily[];
  topNotes: string[];
  heartNotes: string[];
  baseNotes: string[];
  occasion: Occasion[];
  season: Season[];
  longevity: Product['longevity'];
  intensity: Product['intensity'];
  tags: string[];
  description: string;
  similarTo?: string[];
  featured?: boolean;
  lineageId?: string;
  concentration?: string;
};

function inferConcentration(draft: Draft): string | undefined {
  if (draft.concentration) return draft.concentration;
  const source = `${draft.name} ${draft.description}`;
  if (/\bEDP\b/i.test(source)) return 'EDP';
  if (/\bEDT\b/i.test(source)) return 'EDT';
  return undefined;
}

function item(draft: Draft): Product {
  return {
    brandSlug: 'thescentstories',
    bestFor: [],
    similarTo: [],
    ...draft,
    concentration: inferConcentration(draft),
  };
}

